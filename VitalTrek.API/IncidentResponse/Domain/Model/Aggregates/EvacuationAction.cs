using VitalTrek.API.IncidentResponse.Domain.Model.Commands;
using VitalTrek.API.IncidentResponse.Domain.Model.ValueObjects;
using VitalTrek.API.Shared.Domain.Model;

namespace VitalTrek.API.IncidentResponse.Domain.Model.Aggregates;

/// <summary>
///     Aggregate root representing one evacuation step captured by the assigned field guide during a declared emergency.
///     The client generates <see cref="ClientActionId"/> when the step is captured, possibly offline, so every retry of
///     the same capture is recognized; the original author, capture time and content are never overwritten.
/// </summary>
public partial class EvacuationAction
{
    /// <summary>Maximum length allowed for the description.</summary>
    public const int MaximumDescriptionLength = 500;

    /// <summary>Maximum length allowed for the location reference.</summary>
    public const int MaximumLocationLength = 200;

    /// <summary>Gets the server identifier.</summary>
    public int Id { get; private set; }

    /// <summary>Gets the agency that owns the action.</summary>
    public int AgencyId { get; private set; }

    /// <summary>Gets the incident the action belongs to.</summary>
    public int IncidentId { get; private set; }

    /// <summary>Gets the expedition group of the incident.</summary>
    public int ExpeditionGroupId { get; private set; }

    /// <summary>Gets the stable identity generated by the client when the action was captured.</summary>
    public Guid ClientActionId { get; private set; }

    /// <summary>Gets the user that captured the action.</summary>
    public int RecordedByUserId { get; private set; }

    /// <summary>Gets the original capture moment in the field.</summary>
    public DateTimeOffset RecordedAt { get; private set; }

    /// <summary>Gets the moment the platform received the action.</summary>
    public DateTimeOffset SynchronizedAt { get; private set; }

    /// <summary>Gets the description of the evacuation step.</summary>
    public string Description { get; private set; } = string.Empty;

    /// <summary>Gets the optional location reference, such as a checkpoint name or coordinates.</summary>
    public string? Location { get; private set; }

    /// <summary>Gets the state of the step when it was captured.</summary>
    public EvacuationActionStatus Status { get; private set; }

    /// <summary>Gets the fingerprint of the captured content, used to recognize retries and reject reused identities.</summary>
    public string ContentFingerprint { get; private set; } = string.Empty;

    /// <summary>Initializes a new instance of the <see cref="EvacuationAction"/> class for Entity Framework Core.</summary>
    public EvacuationAction()
    {
    }

    /// <summary>Records a captured evacuation step.</summary>
    /// <param name="command">The record evacuation action command.</param>
    /// <param name="expeditionGroupId">The expedition group of the incident.</param>
    /// <param name="recordedByUserId">The authenticated user that captured the action.</param>
    /// <param name="synchronizedAt">The moment the platform receives the action.</param>
    /// <param name="contentFingerprint">The fingerprint of the captured content.</param>
    /// <exception cref="ArgumentException">Thrown when the action data is invalid.</exception>
    public EvacuationAction(RecordEvacuationActionCommand command, int expeditionGroupId, int recordedByUserId,
        DateTimeOffset synchronizedAt, string contentFingerprint)
    {
        AgencyId = DomainGuard.RequirePositive(command.AgencyId, nameof(command.AgencyId));
        IncidentId = DomainGuard.RequirePositive(command.IncidentId, nameof(command.IncidentId));
        ExpeditionGroupId = DomainGuard.RequirePositive(expeditionGroupId, nameof(expeditionGroupId));
        RecordedByUserId = DomainGuard.RequirePositive(recordedByUserId, nameof(recordedByUserId));
        if (command.ClientActionId == Guid.Empty)
            throw new ArgumentException("ClientActionId is required.", nameof(command));
        if (!Enum.IsDefined(command.Status))
            throw new ArgumentException("Status is not a known evacuation action status.", nameof(command));
        if (command.RecordedAt > synchronizedAt + Incident.ClockTolerance)
            throw new ArgumentException("RecordedAt cannot be in the future.", nameof(command));
        ClientActionId = command.ClientActionId;
        Description = DomainGuard.RequireText(command.Description, MaximumDescriptionLength, nameof(command.Description));
        Location = string.IsNullOrWhiteSpace(command.Location)
            ? null
            : DomainGuard.RequireText(command.Location, MaximumLocationLength, nameof(command.Location));
        Status = command.Status;
        RecordedAt = command.RecordedAt.ToUniversalTime();
        SynchronizedAt = synchronizedAt;
        ContentFingerprint = DomainGuard.RequireText(contentFingerprint, 64, nameof(contentFingerprint));
    }
}
