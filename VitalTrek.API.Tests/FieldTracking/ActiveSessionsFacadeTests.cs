namespace VitalTrek.API.Tests.FieldTracking;

/// <summary>
///     The active sessions exposed for periodic server work carry only identifiers and keep the order and limit of the
///     repository.
/// </summary>
public class ActiveSessionsFacadeTests
{
    private int? _requestedCount;

    [Fact]
    public async Task ReturnsOnlyTheIdentifiersOfTheActiveSessionsInRepositoryOrder()
    {
        var sessions = new[] { Session(3, agencyId: 1, groupId: 5), Session(8, agencyId: 2, groupId: 9) };

        var active = await Facade(sessions).FindActiveSessionsAsync(50);

        Assert.Equal(new[] { new ActiveTrackingSession(3, 1, 5), new ActiveTrackingSession(8, 2, 9) }, active);
        Assert.Equal(50, _requestedCount);
    }

    [Theory]
    [InlineData(0)]
    [InlineData(-1)]
    public async Task NonPositiveCountReturnsNothingWithoutQuerying(int maxCount)
    {
        Assert.Empty(await Facade([]).FindActiveSessionsAsync(maxCount));
        Assert.Null(_requestedCount);
    }

    // The identifier is generated by the database; tests assign it the way Entity Framework Core does.
    private static TrackingSession Session(int id, int agencyId, int groupId)
    {
        var session = new TrackingSession(new StartTrackingSessionCommand(agencyId, groupId),
            new DateTimeOffset(2026, 11, 26, 9, 0, 0, TimeSpan.FromHours(-5)));
        typeof(TrackingSession).GetProperty(nameof(TrackingSession.Id))!.SetValue(session, id);
        return session;
    }

    private FieldTrackingContextFacade Facade(IReadOnlyList<TrackingSession> sessions) =>
        new(InterfaceStub<ITrackingSessionRepository>.Create((method, args) =>
            {
                if (method.Name != nameof(ITrackingSessionRepository.FindActiveAsync))
                    throw new InvalidOperationException(method.Name);
                _requestedCount = (int)args[0]!;
                return Task.FromResult(sessions);
            }),
            InterfaceStub<IExpeditionSetupContextFacade>.Create(),
            InterfaceStub<ITelemetryRecordCommandService>.Create());
}
